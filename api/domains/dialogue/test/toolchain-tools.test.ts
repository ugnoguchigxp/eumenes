import { expect, test } from "bun:test";
import type { ToolchainCard } from "../../capabilities";
import {
	appendConversationPolicy,
	operation,
	reportUnavailableTool,
	toolchainTools,
	unavailable,
} from "../service/conversation-tools";

const card = (
	id: string,
	functionName: string,
	redirects: ToolchainCard["redirects"] = [],
): ToolchainCard => ({
	revisionId: `toolchain:${id}@1`,
	id,
	functionName,
	title: id,
	summary: `${id}の目的`,
	useWhen: [`${id}を使う場面`],
	redirects,
	score: { rank: 1, ftsRank: 1, similarity: null, fromHistory: false },
});
const web = card("web.search", "web_search", [
	{
		when: "ニュースの整理",
		toolchainId: "web.research.codex",
		functionName: "web_research",
	},
]);
const history = card("history.research", "conversation_history");

// Host contract tests: tool calls are supplied, not generated by an LLM.
test("every offered toolchain function takes one flat request object", () => {
	for (const tool of toolchainTools([web, history])) {
		const schema = tool.function.parameters as Record<string, unknown>;
		expect(schema.type).toBe("object");
		expect("oneOf" in schema || "anyOf" in schema).toBe(false);
		expect(Object.keys(schema.properties as object)).toEqual([
			"request",
			"announcement",
		]);
	}
});

test("a call resolves to the offered toolchain and keeps the request as given", () => {
	const tools = toolchainTools([web, history]);
	expect(
		operation(
			[
				{
					id: "c",
					name: "web_search",
					arguments: JSON.stringify({
						announcement: "確認します。",
						request: "鎌倉の天気",
					}),
				},
			],
			tools,
			[web, history],
		),
	).toEqual({
		kind: "toolchain",
		toolchainId: "web.search",
		revisionId: "toolchain:web.search@1",
		functionName: "web_search",
		request: "鎌倉の天気",
		announcement: "確認します。",
	});
});

test("a function that was not offered, extra arguments or two calls are rejected", () => {
	const tools = toolchainTools([web]);
	const call = (name: string, args: unknown) => ({
		id: name,
		name,
		arguments: JSON.stringify(args),
	});
	expect(() =>
		operation([call("conversation_history", { request: "前の話" })], tools, [
			web,
		]),
	).toThrow("invalid_conversation_operation");
	expect(() =>
		operation([call("web_search", { request: "株価", kind: "web" })], tools, [
			web,
		]),
	).toThrow("invalid_conversation_operation");
	expect(() =>
		operation(
			[
				call("web_search", { request: "a" }),
				call("web_search", { request: "b" }),
			],
			tools,
			[web],
		),
	).toThrow("invalid_conversation_operation");
});

test("a description names another function only when that function is offered", () => {
	const alone = JSON.stringify(toolchainTools([web]));
	expect(alone).not.toContain("web_research");
	const both = JSON.stringify(
		toolchainTools([web, card("web.research.codex", "web_research")]),
	);
	expect(both).toContain("ニュースの整理にはweb_researchを使う");
});

test("the policy is placed before the current request and carries past selections as data", () => {
	const messages = [
		{ role: "system" as const, content: "人格" },
		{ role: "user" as const, content: "鎌倉の天気" },
	];
	appendConversationPolicy(messages, messages[1]!, [
		{ request: "横浜の天気", functionName: "web_search", outcome: "answered" },
	]);
	expect(messages.at(-1)!.content).toBe("鎌倉の天気");
	expect(messages.at(-2)!.role).toBe("system");
	expect(messages.at(-3)!.content).toContain("pastSelections");
	// The fixed layer names no individual toolchain.
	expect(messages.at(-2)!.content).not.toContain("web_search");
	// It tells the model how to say that nothing fits.
	expect(messages.at(-2)!.content).toContain("report_unavailable");
});

test("report_unavailable takes one strict reply and nothing else", () => {
	const parameters = reportUnavailableTool.function.parameters as {
		properties: Record<string, unknown>;
		required: string[];
		additionalProperties: boolean;
	};
	expect(Object.keys(parameters.properties)).toEqual(["reply"]);
	expect(parameters.required).toEqual(["reply"]);
	expect(parameters.additionalProperties).toBe(false);
	const call = (args: string, name = "report_unavailable") => ({
		id: "c",
		name,
		arguments: args,
	});
	expect(unavailable([call('{"reply":"対応できる担当がありません。"}')])).toBe(
		"対応できる担当がありません。",
	);
	// The contract is the spoken reply: the schema and the description say 160 characters and two sentences.
	expect(
		(parameters.properties.reply as { maxLength: number; description: string })
			.maxLength,
	).toBe(160);
	expect(
		(parameters.properties.reply as { description: string }).description,
	).toContain("音声整形後の合計160字以内・2文以内");
	expect(reportUnavailableTool.function.description).toContain("音声");
	expect(reportUnavailableTool.function.description).toContain("160字以内");
	expect(unavailable([call(JSON.stringify({ reply: "あ".repeat(160) }))])).toBe(
		"あ".repeat(160),
	);
	expect(() =>
		unavailable([call(JSON.stringify({ reply: "あ".repeat(161) }))]),
	).toThrow("invalid_conversation_operation");
	// Another function, or several calls, are not an explanation.
	expect(unavailable([call("{}", "web_search")])).toBeUndefined();
	expect(
		unavailable([call('{"reply":"a"}'), call('{"reply":"b"}')]),
	).toBeUndefined();
	for (const args of ["{}", '{"reply":""}', '{"reply":"a","extra":1}', "[1]"])
		expect(() => unavailable([call(args)])).toThrow(
			"invalid_conversation_operation",
		);
});
