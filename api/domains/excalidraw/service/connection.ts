import { readBounded } from "../../../infrastructure/bounded-read";
import type { LocalServiceLease, LocalServicesPort } from "../../larm";
export type DrawingConnection = {
	version: string;
	gatewayUrl: string;
	gatewayOrigin?: string;
	leaseEndpoint: string;
	appToken: string;
	client: LocalServicesPort;
};
type Use = {
	lease?: LocalServiceLease;
	pending?: Promise<LocalServiceLease>;
	version: string;
	config: DrawingConnection;
	active: number;
	lastOperation: number;
	epoch: number;
};
export function drawingConnection(
	get: () => DrawingConnection,
	options: {
		idleMs?: number;
		pollMs?: number;
		clock?: () => number;
		fetch?: typeof fetch;
	} = {},
) {
	const clock = options.clock ?? Date.now,
		uses = new Map<string, Use>();
	const idleMs = options.idleMs ?? 30000;
	async function releaseUse(use: Use) {
		use.epoch++;
		const lease = use.lease;
		use.lease = undefined;
		if (lease) await use.config.client.release(lease.id).catch(() => {});
	}
	async function release(id: string) {
		const use = uses.get(id);
		if (use) await releaseUse(use);
	}
	async function ready(
		id: string,
		signal: AbortSignal,
	): Promise<LocalServiceLease> {
		const config = get();
		let use = uses.get(id);
		if (use && use.version !== config.version)
			throw new Error("excalidraw_connection_settings_changed");
		if (!use) {
			use = {
				version: config.version,
				config,
				active: 0,
				lastOperation: clock(),
				epoch: 0,
			};
			uses.set(id, use);
		}
		use.lastOperation = clock();
		if (use.pending) return use.pending;
		const selected = use,
			epoch = use.epoch;
		const task = (async () => {
			let lease = selected.lease;
			if (lease) {
				const resolved = await config.client.resolve(lease, signal);
				if (
					resolved.status === "ready" &&
					Date.parse(resolved.expiresAt) > clock()
				)
					lease = await config.client.renew(resolved, signal);
				else {
					await config.client.release(lease.id).catch(() => {});
					lease = undefined;
					selected.lease = undefined;
				}
			}
			const currentEpoch = selected.epoch;
			if (!lease)
				lease = await config.client.ensure(
					"excalidraw-host",
					crypto.randomUUID(),
					AbortSignal.timeout(10000),
				);
			selected.lease = lease;
			while (lease.status === "starting") {
				signal.throwIfAborted();
				await new Promise<void>((resolve, reject) => {
					const abort = () => {
						clearTimeout(timer);
						reject(signal.reason);
					};
					const timer = setTimeout(() => {
						signal.removeEventListener("abort", abort);
						resolve();
					}, options.pollMs ?? 250);
					signal.addEventListener("abort", abort, { once: true });
				});
				if (Date.parse(lease.expiresAt) - clock() < 10000)
					lease = await config.client.renew(lease, signal);
				lease = await config.client.resolve(lease, signal);
				selected.lease = lease;
			}
			if (
				lease.status !== "ready" ||
				new URL(lease.endpoint!).href !== new URL(config.leaseEndpoint).href
			)
				throw new Error("excalidraw_binding_unavailable");
			if (
				signal.aborted ||
				selected.epoch !== currentEpoch ||
				get().version !== config.version ||
				epoch !== currentEpoch
			) {
				await config.client.release(lease.id).catch(() => {});
				throw new Error("excalidraw_connection_invalidated");
			}
			selected.lease = lease;
			return lease;
		})();
		selected.pending = task;
		try {
			return await task;
		} catch (e) {
			// A reset may already have installed a new use under this session ID.
			await releaseUse(selected);
			throw e;
		} finally {
			selected.pending = undefined;
		}
	}
	return {
		async ready(id: string, signal: AbortSignal) {
			return ready(id, signal);
		},
		async request(
			id: string,
			path: string,
			signal: AbortSignal,
			init: RequestInit = {},
		) {
			// Paths are generated by the owning domain, never accepted as proxy URLs.
			await ready(id, signal);
			const config = get(),
				use = uses.get(id)!;
			const epoch = use.epoch;
			use.active++;
			use.lastOperation = clock();
			try {
				const response = await (options.fetch ?? fetch)(
					new URL(path, config.gatewayUrl),
					{
						...init,
						signal,
						redirect: "error",
						headers: {
							...init.headers,
							authorization: `Bearer ${config.appToken}`,
							Host: new URL(config.gatewayOrigin ?? config.gatewayUrl).host,
						},
					},
				);
				const bytes = await readBounded(response.body, {
					limit: 18 * 1024 ** 2,
					missing: "excalidraw_empty_response",
					tooLarge: "excalidraw_response_too_large",
					signal,
				});
				if (use.epoch !== epoch || get().version !== config.version)
					throw new Error("excalidraw_connection_invalidated");
				// An error body need not be JSON; its status is what callers act on.
				if (!response.ok)
					throw new Error(
						response.status === 409
							? "excalidraw_revision_conflict"
							: `excalidraw_http_${response.status}`,
					);
				return JSON.parse(new TextDecoder().decode(bytes)) as unknown;
			} finally {
				use.active--;
				use.lastOperation = clock();
			}
		},
		async activity(id: string) {
			const use = uses.get(id);
			if (use) use.lastOperation = clock();
			// Actual gestures trigger this, never a visibility/status timer.
			await ready(id, AbortSignal.timeout(180000));
		},
		release,
		async reset(id: string) {
			await release(id);
			uses.delete(id);
		},
		async tick() {
			const released: string[] = [];
			for (const [id, use] of uses) {
				if (
					!use.active &&
					!use.pending &&
					use.lease &&
					clock() - use.lastOperation >= idleMs
				) {
					await release(id);
					released.push(id);
				}
			}
			return released;
		},
		async close() {
			await Promise.all([...uses.keys()].map(release));
		},
	};
}
