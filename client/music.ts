import {
	trackQueryParams,
	musicTrack,
	musicTracks,
	musicTags,
	musicProviders,
	type TrackQuery,
} from "../api/domains/larm/contracts";
import type { z } from "zod";
import {
	musicRecord,
	playlistRecord,
	playlistUpdate,
	trackGeneration,
} from "../api/domains/music/contracts";
import {
	ApiError,
	callJson,
	json,
	withQuery,
	type Transport,
} from "./transport";
export function musicClient(t: Transport) {
	return {
		musicProviders: async (signal?: AbortSignal) =>
			callJson(t, musicProviders, "/api/music/providers", { signal }),
		musicPlaylists: async (conversationId: string, signal?: AbortSignal) =>
			callJson(
				t,
				playlistRecord.array(),
				withQuery("/api/music/playlists", { conversationId }),
				{ signal },
			),
		musicPlaylist: async (id: string, signal?: AbortSignal) =>
			callJson(
				t,
				playlistRecord,
				`/api/music/playlists/${encodeURIComponent(id)}`,
				{ signal },
			),
		updateMusicPlaylist: async (
			id: string,
			value: z.infer<typeof playlistUpdate>,
		) =>
			callJson(
				t,
				playlistRecord,
				`/api/music/playlists/${encodeURIComponent(id)}`,
				json(value, "PUT"),
			),
		musicTracks: async (query: TrackQuery, signal?: AbortSignal) =>
			callJson(
				t,
				musicTracks,
				withQuery("/api/music/tracks", trackQueryParams(query)),
				{ signal },
			),
		musicTags: async (signal?: AbortSignal) =>
			callJson(t, musicTags, "/api/music/tags", { signal }),
		musicTrack: async (id: string, signal?: AbortSignal) =>
			callJson(t, musicTrack, `/api/music/tracks/${encodeURIComponent(id)}`, {
				signal,
			}),
		/** null when the track was not generated by Eumenes. */
		musicTrackGeneration: async (id: string, signal?: AbortSignal) => {
			try {
				return await callJson(
					t,
					trackGeneration,
					`/api/music/tracks/${encodeURIComponent(id)}/generation`,
					{ signal },
				);
			} catch (error) {
				if (error instanceof ApiError && error.status === 404) return null;
				throw error;
			}
		},
		musicFavorite: async (id: string, favorite: boolean) => {
			await t.call(`/api/music/tracks/${encodeURIComponent(id)}/favorite`, {
				method: favorite ? "PUT" : "DELETE",
			});
		},
		deleteMusicTrack: async (id: string) => {
			await t.call(`/api/music/tracks/${encodeURIComponent(id)}`, {
				method: "DELETE",
			});
		},

		musicList: async (conversationId: string, signal?: AbortSignal) =>
			callJson(
				t,
				musicRecord.array(),
				withQuery("/api/music", { conversationId }),
				{ signal },
			),
		music: async (id: string, signal?: AbortSignal) =>
			callJson(t, musicRecord, `/api/music/${encodeURIComponent(id)}`, {
				signal,
			}),
		musicAudio: async (id: string, signal?: AbortSignal) =>
			(
				await t.call(`/api/music/${encodeURIComponent(id)}/audio`, { signal })
			).blob(),
		generateMusicArtwork: async (id: string) =>
			callJson(t, musicRecord, `/api/music/${encodeURIComponent(id)}/artwork`, {
				method: "POST",
			}),
		musicArtwork: async (id: string, signal?: AbortSignal) =>
			(
				await t.call(`/api/music/${encodeURIComponent(id)}/artwork`, {
					signal,
				})
			).blob(),
	};
}
