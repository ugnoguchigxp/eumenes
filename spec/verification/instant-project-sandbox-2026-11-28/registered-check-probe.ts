// P0 trusted bridge. Reuse the registered Bash check and its exit/input evidence.
// Replace only the launch envelope in the fixture, so there is one OS profile.
import { strict as assert } from "node:assert";
import { readFileSync, writeFileSync } from "node:fs";
import { resolve } from "node:path";
import { claudeStart, type ClaudeCheck } from "../../../packages/coding-runner/src/claude-contracts";
import {
	claudeCheckRequest, createCheckSandbox, supervisedTools,
} from "../../../packages/coding-runner/src/claude-supervised-tools";

const [workspace, bun, profile, ...args] = process.argv.slice(2);
const source = resolve(workspace!, "src", "main.tsx");
const check: ClaudeCheck = { cwd: workspace!, executable: bun!, args };
const deadline = Date.now() + 60_000;
const execution = claudeStart.parse({
	id: crypto.randomUUID(), workId: crypto.randomUUID(), generation: 0,
	instruction: "P0 registered verification fixture",
	priorExecutionId: null, deadline, maxTurns: 1, readOnly: true,
	supervised: {
		lease: { ownerRef: "fixture", executorId: "fixture", epoch: "1", slot: "exclusive" },
		authorization: {
			workspaceRef: "fixture", mode: "verify", targetRevision: "1.0", deadline,
			readablePaths: [source], writablePaths: [], checks: [check],
		},
	},
});
assert.ok(execution.supervised);
const guard = supervisedTools({ ...execution, supervised: execution.supervised }, workspace!);
let witness: ReturnType<typeof createCheckSandbox> | undefined;
try {
	const request = guard.toolRequest("Bash", { command: claudeCheckRequest(check) });
	assert.ok(request);
	assert.equal(guard.toolRequest("Bash", {
		command: claudeCheckRequest({ ...check, args: [...args, "unregistered"] }),
	}), undefined);

	// The profile is generated by the trusted fixture launcher. The registered
	// command exposes neither the profile nor arbitrary paths to Claude.
	witness = createCheckSandbox(workspace!, crypto.randomUUID());
	const wrapped = witness.withExitStatus(claudeCheckRequest({
		cwd: workspace!, executable: "/usr/bin/sandbox-exec",
		args: ["-p", profile!, bun!, ...args],
	}));
	const child = Bun.spawnSync(["/bin/sh", "-c", wrapped.command], {
		cwd: workspace!,
		env: { PATH: "/usr/bin:/bin" },
	});
	const evidenceRequest = { ...request, statusPath: wrapped.statusPath, stderrPath: wrapped.stderrPath };
	const outputs = { stdout: child.stdout.toString(), stderr: child.stderr.toString() };
	const evidence = guard.toolEvidence(evidenceRequest, outputs, child.exitCode === 0);
	assert.equal(evidence?.exitCode, child.exitCode);
	assert.equal(evidence?.passed, child.exitCode === 0);

	const original = readFileSync(source, "utf8");
	try {
		writeFileSync(source, original + "\n// fixture changed externally");
		assert.equal(guard.toolEvidence(evidenceRequest, outputs, true)?.passed, false);
	} finally {
		writeFileSync(source, original);
	}

	console.log(JSON.stringify({
		worker: JSON.parse(outputs.stdout),
		registeredCheckAccepted: true,
		unregisteredArgsRejected: true,
		exitCode: evidence?.exitCode,
		passed: evidence?.passed,
		changedInputCannotPass: true,
	}));
} finally {
	witness?.cleanup();
	guard.cleanup?.();
}
