import { chromium, expect } from "@playwright/test";
import { writeFileSync } from "node:fs";
const root = import.meta.dir;
const browser = await chromium.launch({ headless: true });
const page = await browser.newPage({ viewport: { width: 1100, height: 780 } });
const errors: string[] = [];
page.on("pageerror", error => errors.push(error.message));
const open = (id: string) => page.goto(`http://127.0.0.1:6087/iframe.html?id=${id}&viewMode=story`);
const audio = () => page.locator("audio").evaluate((node: HTMLAudioElement) => ({ time: node.currentTime, duration: node.duration, paused: node.paused }));
try {
	await open("components-musicplayer--with-playlist");
	const seek = page.getByRole("slider", { name: "再生位置" });
	await expect(seek).toBeEnabled();
	await page.getByRole("button", { name: "再生", exact: true }).click();
	await expect.poll(async () => (await audio()).time).toBeGreaterThan(0.2);
	await page.getByRole("button", { name: "一時停止", exact: true }).click();
	await expect.poll(async () => (await audio()).paused).toBe(true);
	await seek.focus(); await page.keyboard.press("Home");
	await page.getByRole("button", { name: "10秒スキップ" }).click();
	await expect.poll(async () => (await audio()).time).toBeCloseTo(10, 0);
	await page.getByRole("button", { name: "10秒巻き戻し" }).click();
	await expect.poll(async () => (await audio()).time).toBe(0);
	await seek.focus(); await page.keyboard.press("ArrowRight");
	await expect.poll(async () => (await audio()).time).toBeGreaterThan(0);
	await page.getByRole("button", { name: "次の楽曲" }).click();
	await expect(page.getByRole("heading", { name: "Soft Motion" })).toBeVisible();
	await page.getByRole("button", { name: "前の楽曲" }).click();
	await expect(page.getByRole("heading", { name: "Evening Current" })).toBeVisible();
	await page.getByRole("button", { name: /Quiet Orbit/ }).click();
	await expect(page.getByRole("heading", { name: "Quiet Orbit" })).toBeVisible();
	await expect(page.getByRole("button", { name: /Quiet Orbit/ })).toHaveAttribute("aria-current", "true");
	await page.getByRole("button", { name: "再生", exact: true }).click();
	await expect.poll(async () => (await audio()).paused).toBe(false);
	await page.getByRole("button", { name: "次の楽曲" }).click();
	await expect(page.getByRole("heading", { name: "Morning Light" })).toBeVisible();
	await expect.poll(async () => (await audio()).time).toBeGreaterThan(0.2);
	await page.getByRole("button", { name: "一時停止", exact: true }).click();
	await page.screenshot({ path: `${root}/player-playlist.png`, fullPage: true });
	const media = await audio();
	await page.setViewportSize({ width: 360, height: 860 });
	await expect.poll(() => page.evaluate(() => document.documentElement.scrollWidth <= window.innerWidth)).toBe(true);
	await page.screenshot({ path: `${root}/player-narrow.png`, fullPage: true });
	await page.setViewportSize({ width: 700, height: 420 });
	await open("components-generationstatus--music");
	await expect(page.getByRole("status")).toContainText("楽曲を生成しています");
	await expect(page.getByRole("progressbar")).toHaveCount(0);
	await page.screenshot({ path: `${root}/generation-loading.png`, fullPage: true });
	await open("components-generationstatus--image");
	await expect(page.getByRole("progressbar")).toHaveAttribute("value", "62");
	await expect(errors).toEqual([]);
	writeFileSync(`${root}/browser-result.json`, JSON.stringify({ result: "passed", media, checks: ["play", "pause", "seek keyboard", "+10s", "-10s", "next", "previous", "playlist selection", "playing track transition", "360px no overflow", "indeterminate generation", "measured generation progress"], errors }, null, 2));
	console.log("PASS: 12 browser checks", media);
} finally { await browser.close(); }
